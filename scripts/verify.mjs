if(imageFailures || errors.length) throw new Error(JSON.stringify({imageFailures,errors}));
await page.evaluate(() => localStorage.clear());
await browser.close();
console.log('通过：37 张素材、搜索、来源筛选、详情开关、收藏与评论持久化、PC 宽度检查，无运行时错误。');

